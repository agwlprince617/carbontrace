"""Evaluate literal fixture assertions; never exec or eval supplied Python."""

from __future__ import annotations

from copy import deepcopy
from functools import lru_cache
from typing import Literal

from carbontrace.benchmarks import EXERCISES, Target, TestCase
from carbontrace.domain import AssertionResult, MutationResult, QualityResult

Profile = Literal["compact", "strong"]


def check_assertion(target: Target, case: TestCase) -> AssertionResult:
    """Run a project-owned function against a literal assertion.

    Argument copies keep a defective implementation from contaminating later
    checks. This function is not a sandbox for untrusted generated Python.
    """
    try:
        observed = target(*deepcopy(case.args))
    except Exception as error:
        passed = case.raises is not None and isinstance(error, case.raises)
        return AssertionResult(
            title=case.title,
            passed=passed,
            detail=f"Raised {type(error).__name__}",
        )
    if case.raises is not None:
        return AssertionResult(
            title=case.title,
            passed=False,
            detail=f"Expected {case.raises.__name__}; returned {observed!r}",
        )
    return AssertionResult(
        title=case.title,
        passed=observed == case.expected,
        detail=f"Expected {case.expected!r}; received {observed!r}",
    )


@lru_cache(maxsize=64)
def evaluate_suite(task_id: str, profile: Profile) -> QualityResult:
    """Actually run all fixture assertions against reference and seeded bugs."""
    exercise = EXERCISES[task_id]
    cases = exercise.compact_cases if profile == "compact" else exercise.strong_cases
    assertions = [check_assertion(exercise.function, case) for case in cases]
    mutations = [
        MutationResult(
            name=mutation.name,
            description=mutation.description,
            detected=any(
                not check_assertion(mutation.target, case).passed for case in cases
            ),
        )
        for mutation in exercise.mutations
    ]
    detected = sum(result.detected for result in mutations)
    return QualityResult(
        assertions=assertions,
        mutations=mutations,
        correct_implementation_passes=all(result.passed for result in assertions),
        detected=detected,
        total_mutations=len(mutations),
        detection_percent=100 * detected / len(mutations),
    )


def render_suite(task_id: str, profile: Profile) -> str:
    """Render the same literal assertions as a runnable pytest module."""
    exercise = EXERCISES[task_id]
    cases = exercise.compact_cases if profile == "compact" else exercise.strong_cases
    lines = [
        '"""Hand-authored CarbonTrace fixture. Not generated by a live model."""',
        "import pytest",
        f"from subject import {exercise.function.__name__} as subject",
        "",
    ]
    for index, case in enumerate(cases, start=1):
        arguments = ", ".join(repr(argument) for argument in case.args)
        lines += ["", f"def test_case_{index}():", f"    # {case.title}"]
        if case.raises:
            lines += [
                f"    with pytest.raises({case.raises.__name__}):",
                f"        subject({arguments})",
            ]
        else:
            lines += [f"    assert subject({arguments}) == {case.expected!r}"]
    return "\n".join(lines) + "\n"
